import { Sequelize } from "sequelize-typescript";
import request from "supertest";
import { setupDatabase } from "../../db/sequelize";
import { app } from "../express";
import { clientPayload, createClient, createProduct } from "../test-utils/e2e-helpers";

describe("E2E test for invoice", () => {
  let sequelize: Sequelize;

  beforeEach(async () => {
    sequelize = await setupDatabase();
  });

  afterEach(async () => {
    await sequelize.close();
  });

  it("should find the invoice generated by the checkout", async () => {
    await createClient("c1");
    await createProduct("p1", 100);
    await createProduct("p2", 50);
    const checkout = await request(app)
      .post("/checkout")
      .send({
        clientId: "c1",
        products: [{ productId: "p1" }, { productId: "p2" }],
      });
    const invoiceId = checkout.body.invoiceId;

    const response = await request(app).get(`/invoice/${invoiceId}`);

    expect(response.status).toBe(200);
    expect(response.body.id).toBe(invoiceId);
    expect(response.body.name).toBe(clientPayload.name);
    expect(response.body.document).toBe(clientPayload.document);
    expect(response.body.address).toEqual(clientPayload.address);
    expect(response.body.items).toHaveLength(2);
    expect(response.body.items).toEqual(
      expect.arrayContaining([
        { id: "p1", name: "Product p1", price: 100 },
        { id: "p2", name: "Product p2", price: 50 },
      ])
    );
    expect(response.body.total).toBe(150);
    expect(response.body.createdAt).toBeDefined();
  });

  it("should return 404 when invoice does not exist", async () => {
    const response = await request(app).get("/invoice/not-exists");

    expect(response.status).toBe(404);
    expect(response.body.message).toBe("Invoice with id not-exists not found");
  });
});
